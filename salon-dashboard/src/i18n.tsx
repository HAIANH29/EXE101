type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: string, params?: Record<string, string | number>) => string;
  money: (value: number | string | undefined) => string;
  dateTime: (value: string) => string;
  date: (value: string) => string;
  statusLabel: (status: BackendBookingStatus) => string;
};

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

function readStoredLanguage(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === 'en' ? 'en' : 'vi';
  } catch {
    return 'vi';
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(readStoredLanguage);

  const value = useMemo<I18nContextValue>(() => {
    const setLanguage = (nextLanguage: Language) => {
      setLanguageState(nextLanguage);
      try {
        localStorage.setItem(STORAGE_KEY, nextLanguage);
      } catch {
        // Ignore storage errors in private browsing modes.
      }
    };

    const t = (key: string, params?: Record<string, string | number>) => {
      const template = translations[language][key] || translations.vi[key] || key;
      if (!params) return template;
      return Object.entries(params).reduce(
        (text, [paramKey, value]) => text.replaceAll(`{${paramKey}}`, String(value)),
        template
      );
    };

    const locale = language === 'vi' ? 'vi-VN' : 'en-US';

    return {
      language,
      setLanguage,
      toggleLanguage: () => setLanguage(language === 'vi' ? 'en' : 'vi'),
      t,
      money: (value) => `${Number(value || 0).toLocaleString(locale)} đ`,
      dateTime: (value) => new Date(value).toLocaleString(locale),
      date: (value) => new Date(value).toLocaleDateString(locale),
      statusLabel: (status) => statusLabels[language][status] || status
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }
  return context;
}
